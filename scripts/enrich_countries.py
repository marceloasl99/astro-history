def enrich():
    target_path = "/home/astro/data/countries_database.json"
    with open(target_path, "r", encoding="utf-8") as f:
        existing = json.load(f)
    existing_isos = {c["iso_code"] for c in existing}
    added = 0
    for c in MORE_COUNTRIES:
        if c["iso_code"] not in existing_isos:
            existing.append(c)
            existing_isos.add(c["iso_code"])
            added += 1
    existing.sort(key=lambda x: x["name_pt"])
    with open(target_path, "w", encoding="utf-8") as f:
        json.dump(existing, f, indent=2, ensure_ascii=False)
    print(f"Adicionados {added} novos países. Total consolidado: {len(existing)} países em {target_path}")

if __name__ == "__main__":
    enrich()
